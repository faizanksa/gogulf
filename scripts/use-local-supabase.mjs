/**
 * Point local Next.js at LOCAL Supabase, without touching .env.local.
 *
 * Writes .env.development.local and .env.production.local from the running
 * local stack (`npx supabase start`). Next.js loads those ahead of .env.local
 * for `next dev` and `next build`/`next start` respectively, so their Supabase
 * values win over anything in .env.local.
 *
 * .env.local is deliberately left alone. It no longer holds production Supabase
 * keys — those live in .env.prod-supabase.local, which nothing loads implicitly
 * (see docs/STAGING.md §8).
 *
 *   npx supabase start
 *   npm run env:local
 *
 * Both files are git-ignored (`.env*`). The keys written are the local stack's
 * development keys, which only work against 127.0.0.1. Values are never printed.
 */

import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const status = spawnSync("npx", ["supabase", "status", "-o", "env"], {
  encoding: "utf8",
  shell: process.platform === "win32",
});

const vars = {};
for (const line of (status.stdout ?? "").split(/\r?\n/)) {
  const m = line.match(/^([A-Z_]+)=(?:"(.*)"|(.*))$/);
  if (m) vars[m[1]] = m[2] ?? m[3] ?? "";
}

const apiUrl = vars.API_URL;
if (status.status !== 0 || !apiUrl) {
  console.error("Local Supabase is not running. Start it first:\n\n  npx supabase start\n");
  process.exit(1);
}

// Refuse to write anything that is not a loopback address. This script exists to
// point AWAY from hosted projects; it must never be able to point at one.
if (!/^https?:\/\/(127\.0\.0\.1|localhost)(:\d+)?$/i.test(apiUrl)) {
  console.error(`Refusing: supabase status reported a non-local API URL (${apiUrl}).`);
  process.exit(1);
}

const anon = vars.ANON_KEY ?? vars.PUBLISHABLE_KEY;
const service = vars.SERVICE_ROLE_KEY ?? vars.SECRET_KEY;
if (!anon || !service) {
  console.error("Could not read the local anon/service keys from `supabase status`.");
  process.exit(1);
}

const body =
  "# GENERATED by `npm run env:local` — points local Next.js at LOCAL Supabase.\n" +
  "# Loaded by Next.js ahead of .env.local. Safe to delete; regenerate any time.\n" +
  "# Local development keys only — they work against 127.0.0.1 and nowhere else.\n" +
  `NEXT_PUBLIC_SUPABASE_URL=${apiUrl}\n` +
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anon}\n` +
  `SUPABASE_SERVICE_ROLE_KEY=${service}\n` +
  (vars.DB_URL ? `SUPABASE_DB_URL=${vars.DB_URL}\n` : "") +
  "APP_ENV=local\n";

for (const file of [".env.development.local", ".env.production.local"]) {
  writeFileSync(file, body, { encoding: "utf8" });
  console.log(`wrote ${file}`);
}
console.log(
  "\nVariables set (values not shown): NEXT_PUBLIC_SUPABASE_URL, NEXT_PUBLIC_SUPABASE_ANON_KEY," +
    ` SUPABASE_SERVICE_ROLE_KEY${vars.DB_URL ? ", SUPABASE_DB_URL" : ""}, APP_ENV`,
);
console.log(`Local API: ${apiUrl}`);
